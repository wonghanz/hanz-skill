#!/usr/bin/env python3
"""
pipeline.py — Full workflow: CAD images in, photorealistic render(s) out.

    1. Validate input completeness (front/side/dimension views present + legible)
    2. Extract structure (vision_extract.py)
    3. Generate initial render(s) (generate_image.py)
    4. Check consistency against the CAD structure (consistency_check.py)
    5. If hard-fail: retry via targeted edit (edit_image.py), up to MAX_RETRIES
    6. Deliver: final images, plus a note on any assumptions or unresolved mismatch

This is the reference implementation the SKILL.md instructions point to.
It requires DASHSCOPE_API_KEY and network access to Alibaba Cloud Model
Studio, which the Capafy execution environment provides — it will not run
standalone in a sandbox with no internet access to dashscope.aliyuncs.com.
"""

import os
import sys
import json
import argparse

from vision_extract import extract_structure, EXTRACTION_PROMPT
from generate_image import generate_render, generate_render_from_reference
from consistency_check import check_consistency
from edit_image import edit_render

MAX_RETRIES = 3
REQUIRED_VIEWS = ["front view", "side view", "dimension page"]


def validate_input(image_paths, api_key=None):
    """Ask Qwen-VL to classify which required views are present among the uploads.

    Returns (is_complete, missing_list, classification_detail).
    This is a judgment call by the vision model, not a hardcoded filename
    check, because designers name/order their uploads inconsistently.
    """
    api_key = api_key or os.environ.get("DASHSCOPE_API_KEY")
    from dashscope import MultiModalConversation

    prompt = (
        "These images are a furniture designer's CAD upload. Identify which of "
        "the following are present, clearly legible, and usable: a front view, "
        "a side view, and a page with dimension annotations. Any additional "
        "images are component/part (零件) drawings — note how many. Return ONLY "
        'JSON: {"front_view": true|false, "side_view": true|false, '
        '"dimension_page": true|false, "component_drawings_count": <int>, '
        '"notes": "anything blurry/ambiguous"}'
    )
    content = [{"text": prompt}] + [{"image": p} for p in image_paths]
    response = MultiModalConversation.call(
        api_key=api_key, model="qwen3-vl-plus", messages=[{"role": "user", "content": content}]
    )
    if response.status_code != 200:
        raise RuntimeError(f"Input validation call failed: {response.code} - {response.message}")

    raw = response.output.choices[0].message.content
    if isinstance(raw, list):
        raw = "".join(b.get("text", "") for b in raw if isinstance(b, dict))
    raw = raw.strip().strip("`")
    if raw.startswith("json"):
        raw = raw[4:]
    result = json.loads(raw)

    missing = []
    if not result.get("front_view"):
        missing.append("front view")
    if not result.get("side_view"):
        missing.append("side view")
    if not result.get("dimension_page"):
        missing.append("dimension-annotated page")

    return (len(missing) == 0, missing, result)


def _generate_checked_render(structure, material_notes, angle, api_key, reference_image_url=None):
    """Generate one angle for one material version, then run the check+retry-via-edit
    loop on it (up to MAX_RETRIES). Shared by every version so the logic only lives
    once.

    If reference_image_url is given, the angle is generated by conditioning on that
    image (via Qwen-Image-Edit) instead of from text alone — see
    generate_render_from_reference for why this matters."""
    if reference_image_url:
        render = generate_render_from_reference(reference_image_url, structure, material_notes, angle, api_key=api_key)
    else:
        render = generate_render(structure, material_notes, angle, api_key=api_key)
    image_url = render["image_url"]
    attempts = 0
    last_check = None
    steps = [{"step": "initial_generate", "angle": angle, "used_reference": bool(reference_image_url), "result": render}]

    while attempts < MAX_RETRIES:
        check = check_consistency(structure, image_url, api_key=api_key)
        last_check = check
        steps.append({"step": f"consistency_check_attempt_{attempts + 1}", "angle": angle, "result": check})
        if check.get("pass", False):
            break
        edited = edit_render(image_url, check.get("hard_fail_issues", []), api_key=api_key)
        image_url = edited["image_url"]
        attempts += 1
        steps.append({"step": f"edit_attempt_{attempts}", "angle": angle, "result": edited})

    return {
        "angle": angle,
        "image_url": image_url,
        "converged": bool(last_check and last_check.get("pass")),
        "unresolved_issues": [] if (last_check and last_check.get("pass")) else last_check.get("hard_fail_issues", []),
    }, steps


def run_pipeline(image_paths, material_versions=None, angles=None, force_proceed=False, api_key=None):
    """
    material_versions: list of material/color descriptions, one render set per entry,
    e.g. ["walnut, matte black legs", "white oak, brass legs"]. Pass None or an empty
    list to skip the question entirely — the pipeline then generates exactly one
    version, using whatever material_or_color_notes vision_extract found (or a
    labeled default if it found none). This mirrors the "designer can skip and let
    the skill decide" rule: a designer who doesn't care about material variants
    shouldn't have to answer a question about them.
    """
    angles = angles or ["3/4 front view", "side view"]
    versions = material_versions if material_versions else [None]
    log = {"assumptions": [], "steps": []}

    # Step 1: validate
    is_complete, missing, detail = validate_input(image_paths, api_key=api_key)
    log["steps"].append({"step": "validate_input", "result": detail})
    if not is_complete:
        if not force_proceed:
            return {
                "status": "blocked",
                "message": (
                    f"Missing or unreadable: {', '.join(missing)}. "
                    "Please add these before I can generate an accurate render. "
                    "If you'd rather proceed anyway, say so and I'll fill the gaps "
                    "with labeled assumptions."
                ),
                "log": log,
            }
        log["assumptions"].append(f"Proceeded despite missing: {', '.join(missing)} (user override).")

    # Step 2: extract structure (shared across every version — the CAD only gets read once)
    structure = extract_structure(image_paths, api_key=api_key)
    log["steps"].append({"step": "extract_structure", "result": structure})
    if structure.get("missing_or_unclear"):
        log["assumptions"].extend(structure["missing_or_unclear"])
    if versions == [None] and not structure.get("material_or_color_notes"):
        log["assumptions"].append("No material/color specified by designer or CAD — using a type-appropriate default.")

    # Steps 3-5: generate + check + retry-via-edit, once per version.
    # Within a version: the first angle is the "hero", generated from text. Every
    # other angle is generated by referencing the hero's final image, so they can't
    # independently drift on details the structure JSON doesn't capture (leg style,
    # hardware, exact material tone). See generate_render_from_reference for why.
    version_results = []
    for material_notes in versions:
        angle_results = []
        hero_image_url = None
        for i, angle in enumerate(angles):
            result, steps = _generate_checked_render(
                structure, material_notes, angle, api_key,
                reference_image_url=hero_image_url if i > 0 else None,
            )
            angle_results.append(result)
            log["steps"].extend(steps)
            if i == 0:
                hero_image_url = result["image_url"]  # use the hero's final (post-retry) image as the reference
        version_results.append({"material": material_notes or "(unspecified — default used)", "renders": angle_results})

    return {"status": "done", "versions": version_results, "structure": structure, "log": log}


def main():
    parser = argparse.ArgumentParser(description="Run the full CAD-to-render pipeline")
    parser.add_argument("images", nargs="+", help="Paths/URLs to CAD views + component drawings")
    parser.add_argument("--materials", nargs="+", default=None, help="One or more material/color descriptions, one render set each. Omit to skip and use a default.")
    parser.add_argument("--angles", nargs="+", default=None)
    parser.add_argument("--force-proceed", action="store_true", help="Proceed even if required views are missing")
    args = parser.parse_args()

    result = run_pipeline(args.images, material_versions=args.materials, angles=args.angles, force_proceed=args.force_proceed)
    print(json.dumps(result, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
